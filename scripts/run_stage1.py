"""Run prespecified old-station eligibility, radius counts, and stack control checks."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import pandas as pd
import yaml

from stimpact.download import sha256
from stimpact.feasibility import radius_feasibility, screen_existing_stations, weekly_departures
from stimpact.io import load_trips
from stimpact.stage1_report import record_results


def run(root: Path) -> dict:
    config = yaml.safe_load((root / "config.yaml").read_text(encoding="utf-8"))
    manifest = json.loads((root / "data/manifest.json").read_text(encoding="utf-8"))
    for entry in manifest["files"]:
        if sha256(root / "data/raw" / entry["filename"]) != entry["sha256"]:
            raise ValueError(f"SHA256 mismatch: {entry['filename']}")
    source = root / "reports/stage0"
    canonical = pd.read_csv(source / "canonical_station_registry.csv", dtype={"station_id": "string"},
                             parse_dates=["analysis_open_date", "first_trip_date", "last_trip_date"])
    id_map = pd.read_csv(source / "station_id_map.csv", dtype={"raw_station_id": "string", "canonical_station_id": "string"})
    treatment = pd.read_csv(source / "treatment_source_stations.csv", dtype={"station_id": "string"},
                             parse_dates=["analysis_open_date", "first_trip_date", "last_trip_date"])
    exposure = pd.read_csv(source / "exposure_source_stations.csv", dtype={"station_id": "string"},
                            parse_dates=["analysis_open_date", "first_trip_date", "last_trip_date"])
    counts, cleaning = [], Counter()
    for entry in manifest["files"]:
        if entry["kind"] != "trip_csv":
            continue
        trips = load_trips(root / "data/raw" / entry["filename"],
                           config["eligibility"]["virtual_station_id"], station_id_map=id_map)
        weekly, audit = weekly_departures(trips, config)
        counts.append(weekly)
        cleaning.update(audit)
        print(f"Eligibility departures: {entry['filename']} ({audit['counted_departures']:,})", flush=True)
    weekly = pd.concat(counts, ignore_index=True)
    eligibility, dense = screen_existing_stations(canonical, weekly, config)
    existing = eligibility.loc[eligibility.eligible].copy()
    radii, assignments, stacks, decision = radius_feasibility(existing, treatment, exposure, config)
    summary = {"treatment_sources": len(treatment), "exposure_sources": len(exposure),
               "canonical_pre2022_stations": len(eligibility), "eligible_existing_stations": len(existing),
               "eligibility_exclusions": eligibility.loc[~eligibility.eligible, "eligibility_reason"].value_counts().to_dict(),
               "cleaning": dict(cleaning), "radii": radii.to_dict(orient="records"), "decision": decision,
               "input_hashes": {name: sha256(source / name) for name in (
                   "canonical_station_registry.csv", "station_id_map.csv", "treatment_source_stations.csv",
                   "exposure_source_stations.csv")}}
    output = root / "reports/stage1"
    output.mkdir(parents=True, exist_ok=True)
    eligibility.to_csv(output / "eligibility_audit.csv", index=False)
    radii.to_csv(output / "radius_counts.csv", index=False)
    assignments.to_csv(output / "radius_station_assignments.csv", index=False)
    stacks.to_csv(output / "stack_control_counts.csv", index=False)
    chosen = decision["radius_from_treated_count_rule_m"]
    failures = stacks.loc[stacks.radius_m.eq(chosen) & ~stacks.passes_min_controls]
    failures.to_csv(output / "failed_stack_controls.csv", index=False)
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    (root / "data/interim").mkdir(parents=True, exist_ok=True)
    dense.to_csv(root / "data/interim/eligibility_weekly_departures.csv", index=False)
    lines = ["# Stage 1 feasibility audit", "", "Generated by `python scripts/run_stage1.py`.", "",
             f"Treatment sources: {len(treatment)}; all operating exposure sources: {len(exposure)}. "
             f"Canonical pre-2022 identities: {len(eligibility)}; eligible existing stations: {len(existing)}. "
             "No treatment-effect estimates or before/after effect comparisons were run.", "",
             "## Existing-station eligibility", "",
             "Canonicalize both endpoints before removing short or same-physical-station trips. "
             "Use the complete Monday-week grid, including zeros. Baseline means use all weeks "
             f"from {config['eligibility']['baseline_first_week']} through "
             f"{config['eligibility']['baseline_last_week']}; the final baseline week includes "
             "2023-01-01. Identity exclusions precede the baseline-volume and inactivity rules. "
             "`eligibility_audit.csv` records every pre-2022 identity and its first failing rule.", "",
             "| Primary exclusion | Stations |", "| --- | ---: |"]
    for reason, count in summary["eligibility_exclusions"].items():
        lines.append(f"| {reason} | {count} |")
    lines += ["", "## Radius counts", "",
              "| R metres | Treated | Never-treated controls | Buffer | Excluded | Minimum controls used across stacks | All stacks pass |",
              "| ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for row in radii.itertuples():
        lines.append(f"| {row.radius_m} | {row.treated_stations} | {row.never_treated_controls} | "
                     f"{row.buffer_stations} | {row.excluded_stations} | "
                     f"{row.minimum_controls_used_per_stack} | {row.all_stacks_have_min_controls} |")
    lines += ["", "Never-treated controls use all exposure sources within 2R. If they are fewer "
              f"than {config['estimation']['min_controls_per_stack']}, each quarterly stack adds "
              "all eligible stations whose first exposure within 2R occurs strictly after its "
              "last calendar week. This is checked on unique stations in every stack, using "
              "actual earliest/latest treated weeks to form the stack window. Counts and failing "
              "cohorts are in `stack_control_counts.csv` and `failed_stack_controls.csv`.", "",
              "## Prespecified decision", "",
              f"The treated-count rule evaluates R = {chosen} metres. Decision: "
              f"**{decision['decision']}**. Reason: `{decision['reason']}`.", ""]
    if decision["decision"] == "redesign_area_level":
        lines += ["The station-level design has not passed its preregistered feasibility gate. "
                  "Keep the 2R buffer and do not switch radius to recover controls or drop failing "
                  "cohorts. The next design must use one-kilometre areas and be specified separately "
                  "before estimation; the station-level preregistration remains unfrozen.", ""]
    else:
        lines += [f"The selected station-level treatment radius is {decision['selected_radius_m']} "
                  "metres. Record this radius and the control mode in the preregistration freeze "
                  "commit before any real-data estimation.", ""]
    lines += ["## Reproduction", "", "```powershell", "python scripts/run_stage0.py --offline",
              "python scripts/run_stage1.py", "```", "",
              "The Stage 0 files are hashed in `summary.json`; original inputs are checked against "
              "the pinned manifest. Eligibility counts conserve cleaned departures on the full "
              "week grid. All radii use positions, dates, and the fixed eligibility rules; no "
              "treatment effects are used for radius selection.", ""]
    (output / "README.md").write_text("\n".join(lines), encoding="utf-8")
    record_results(root, summary, stacks, assignments)
    print(json.dumps(summary, indent=2), flush=True)
    return summary


if __name__ == "__main__":
    run(Path(__file__).resolve().parents[1])
